#!/usr/bin/env python3
"""Generate synthetic production-line data for the SPC dashboard demo.

Every value in the output file is SYNTHETIC — generated with a fixed random
seed so the file is reproducible. No real production data, no real company
data, and no Tesla data is used anywhere in this project.

Design (matches the Tesla NCM Process Technician JD themes):
- 2 production lines x 4 weeks, ~5,000 units total.
- Columns: date, line, shift, unit_id, defect_category, dimension_mm
  (dimension_mm is the critical dimension, nominal 10.00 mm,
  spec limits 9.90 - 10.10 mm).
- Realistic defect mix: scratch / contamination / crack / dimension / other.
- One deliberately out-of-control period: Line B, week 3 (2026-10-19 to
  2026-10-22), where the process mean shifts upward and the defect rate
  spikes — so the X-bar chart shows points beyond the control limits and
  the Pareto / yield numbers move. This is the "out-of-control process"
  the dashboard is built to catch.

Usage:
    python scripts/generate_sample_data.py
    python scripts/generate_sample_data.py --output data/sample_production.csv
"""

import argparse
import csv
import random

SEED = 42
NOMINAL = 10.00
SIGMA = 0.02

# (start_day_offset, end_day_offset, line, mean_shift, defect_rate)
OUT_OF_CONTROL = (14, 17, "Line B", 0.06, 0.09)

BASE_DEFECT_RATE = 0.025
DEFECT_MIX = [
    ("scratch", 0.35),
    ("contamination", 0.25),
    ("crack", 0.15),
    ("dimension", 0.15),
    ("other", 0.10),
]
# During the out-of-control period dimension defects dominate.
OOC_DEFECT_MIX = [
    ("dimension", 0.55),
    ("scratch", 0.20),
    ("contamination", 0.15),
    ("crack", 0.05),
    ("other", 0.05),
]

SHIFTS = ["Day", "Swing", "Night"]
LINES = ["Line A", "Line B"]
START_DATE = "2026-10-05"  # Monday, week 1
DAYS = 28


def pick_defect(rng, mix):
    r = rng.random()
    cumulative = 0.0
    for category, weight in mix:
        cumulative += weight
        if r <= cumulative:
            return category
    return mix[-1][0]


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--output", default="data/sample_production.csv",
        help="Path to write the CSV to (default: data/sample_production.csv)",
    )
    args = parser.parse_args()

    rng = random.Random(SEED)

    from datetime import date, timedelta

    start = date.fromisoformat(START_DATE)
    ooc_start, ooc_end, ooc_line, ooc_shift, ooc_rate = OUT_OF_CONTROL

    rows = []
    unit = 0
    for day in range(DAYS):
        current = start + timedelta(days=day)
        for line in LINES:
            # ~85-95 units per line per day -> ~5,000 units over 4 weeks.
            n_units = rng.randint(85, 95)
            in_ooc = (
                line == ooc_line and ooc_start <= day <= ooc_end
            )
            mean = NOMINAL + (ooc_shift if in_ooc else 0.0)
            defect_rate = ooc_rate if in_ooc else BASE_DEFECT_RATE
            mix = OOC_DEFECT_MIX if in_ooc else DEFECT_MIX
            for _ in range(n_units):
                unit += 1
                shift = SHIFTS[(unit + day) % len(SHIFTS)]
                dimension = rng.gauss(mean, SIGMA)
                if rng.random() < defect_rate:
                    defect = pick_defect(rng, mix)
                else:
                    defect = "none"
                rows.append(
                    {
                        "date": current.isoformat(),
                        "line": line,
                        "shift": shift,
                        "unit_id": f"U{unit:05d}",
                        "defect_category": defect,
                        "dimension_mm": f"{dimension:.4f}",
                    }
                )

    with open(args.output, "w", newline="") as f:
        f.write(
            "# SYNTHETIC DATA - generated by scripts/generate_sample_data.py "
            "(seed 42). Not real production data.\n"
        )
        writer = csv.DictWriter(
            f,
            fieldnames=[
                "date",
                "line",
                "shift",
                "unit_id",
                "defect_category",
                "dimension_mm",
            ],
        )
        writer.writeheader()
        writer.writerows(rows)

    n_defects = sum(1 for r in rows if r["defect_category"] != "none")
    print(f"Wrote {len(rows)} units to {args.output}")
    print(f"Defects: {n_defects} ({100 * n_defects / len(rows):.2f}%)")
    print(
        "Out-of-control period baked in: Line B, 2026-10-19 to 2026-10-22 "
        "(mean shift +0.06 mm, defect rate 9%)."
    )


if __name__ == "__main__":
    main()
